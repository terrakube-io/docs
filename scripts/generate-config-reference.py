#!/usr/bin/env python3
"""Generate the configuration reference pages from Terrakube's application.properties files.

Usage:
    scripts/generate-config-reference.py <terrakube checkout> [--ref <git ref>]

Reads api/executor/registry application.properties from the checkout (at --ref
if given, otherwise the working tree) and writes
user-guide/reference/configuration/{api,executor,registry}.md.
Every setting written as ${EnvVar:default} becomes a row; the comment lines
directly above it become the description.
"""
import re
import subprocess
import sys
from pathlib import Path

SERVICES = {
    "api": ("API", "api/src/main/resources/application.properties"),
    "executor": ("Executor", "executor/src/main/resources/application.properties"),
    "registry": ("Registry", "registry/src/main/resources/application.properties"),
}

def first_var(value):
    """Return (env name, default or None) of the first ${...} in value, honouring nested braces."""
    start = value.find("${")
    if start < 0:
        return None
    depth, i = 0, start + 2
    depth = 1
    while i < len(value) and depth:
        depth += {"{": 1, "}": -1}.get(value[i], 0)
        i += 1
    inner = value[start + 2 : i - 1]
    name, sep, default = inner.partition(":")
    return name, (default if sep else None)

OUT = Path(__file__).resolve().parent.parent / "user-guide" / "reference" / "configuration"


def read(checkout, rel, ref):
    if ref:
        return subprocess.check_output(["git", "-C", checkout, "show", f"{ref}:{rel}"], text=True)
    return (Path(checkout) / rel).read_text()


def clean(text):
    text = re.sub(r"\s+", " ", text).strip().replace("|", "\\|")
    text = re.sub(r"\(see [^)]*\.md\)", "", text).strip()
    if len(text) > 240:
        cut = text[:240]
        text = cut[: cut.rfind(". ") + 1] if ". " in cut else cut.rsplit(" ", 1)[0] + "..."
    return text


def parse(text):
    section, comments, rows, seen = "General", [], [], set()
    for line in text.splitlines():
        s = line.strip()
        if not s:
            comments = []
            continue
        if s.startswith("#"):
            body = s.lstrip("#").strip()
            if not body:
                comments = []
                continue
            if re.fullmatch(r"#+", s.replace(" ", "")) is None and s.endswith("#") and s.startswith("#") and body.rstrip("# ").strip():
                section = re.sub(r"\s*\(.*?\)", "", body.rstrip("# ").strip()).strip()
                section = section[:1].upper() + section[1:]
                comments = []
                continue
            comments.append(body)
            continue
        if "=" not in s:
            comments = []
            continue
        key, value = s.split("=", 1)
        m = first_var(value)
        if m and m[0] not in seen:
            env, default = m
            seen.add(env)
            if default is None:
                default = ""
            rows.append((section, env, default, key.strip(), clean(" ".join(comments))))
        comments = []
    return rows


def render(title, rows, ref):
    out = [f"# {title} configuration", "",
           f"<!-- Generated by scripts/generate-config-reference.py from Terrakube {ref}. Do not edit by hand. -->", "",
           f"Environment variables of the Terrakube **{title}**. See [Configuration Reference](README.md) for how to set them. "
           "An empty default means the variable has no default: either it is optional or it must be provided.", ""]
    sections = []
    for r in rows:
        if r[0] not in sections:
            sections.append(r[0])
    for sec in sections:
        out += [f"### {sec}", "", "| Variable | Default | Description |", "| --- | --- | --- |"]
        for _, env, default, prop, desc in (r for r in rows if r[0] == sec):
            d = f"`{default}`" if default else ""
            out.append(f"| `{env}` | {d} | {desc or f'Sets `{prop}`.'} |")
        out.append("")
    return "\n".join(out)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    checkout = sys.argv[1]
    ref = sys.argv[sys.argv.index("--ref") + 1] if "--ref" in sys.argv else None
    label = ref or "the working tree"
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (title, rel) in SERVICES.items():
        rows = parse(read(checkout, rel, ref))
        (OUT / f"{name}.md").write_text(render(title, rows, label))
        print(f"{name}: {len(rows)} settings")


if __name__ == "__main__":
    main()
